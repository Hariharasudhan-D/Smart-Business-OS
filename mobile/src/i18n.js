/** The app is English only; kept as a hook so screens stay unchanged. */
export function LangProvider({ children }) {
  return children;
}

export function useLang() {
  return { t };
}

/** Turns an API error into a short sentence. */
export function errorText(t, err) {
  if (err?.code === 'offline') return t.offline;
  if (err?.code === 'timeout') return t.timeout;
  if (err?.code === 401) return t.wrongLogin;
  if (err?.code === 403) return t.notAdmin;
  return err?.message && !err.message.startsWith('http_') ? err.message : t.somethingWrong;
}
